"""Generate docs/schema.md and docs/quality-flags.md from the code.

The field descriptions in form4clean.models.transaction and the flag registry in
form4clean.validation.flags are the source of truth. Run this after changing either:

    python scripts/generate_docs.py

The test suite fails if the committed docs are out of date.
"""

from __future__ import annotations

import sys
from pathlib import Path

import polars as pl

from form4clean.classification.codes import CODES
from form4clean.models.schema import CLEAN_SCHEMA
from form4clean.models.transaction import InsiderTransaction
from form4clean.validation.flags import FLAGS
from form4clean.versions import CLEANING_VERSION, SCHEMA_VERSION

DOCS = Path(__file__).resolve().parent.parent / "docs"
HEADER = "<!-- Generated by scripts/generate_docs.py. Do not edit by hand. -->\n\n"


def _type(dtype: pl.DataType) -> str:
    if isinstance(dtype, pl.Decimal):
        return f"decimal({dtype.precision}, {dtype.scale})"
    if isinstance(dtype, pl.Datetime):
        return f"timestamp ({dtype.time_zone})"
    if isinstance(dtype, pl.List):
        inner = dtype.inner
        if isinstance(inner, pl.Struct):
            return "list of {" + ", ".join(f.name for f in inner.fields) + "}"
        return f"list of {_type(inner).lower()}"
    names = {pl.String: "string", pl.Int32: "integer", pl.Boolean: "boolean", pl.Date: "date"}
    for k, v in names.items():
        if dtype == k:
            return v
    return str(dtype)


def schema_md() -> str:
    lines = [
        HEADER,
        "# Dataset schema\n\n",
        f"Schema version **{SCHEMA_VERSION}**, produced by cleaning version "
        f"**{CLEANING_VERSION}**. One row per transaction row in a source filing.\n\n",
        "* Money and quantities are exact decimals, never floating point.\n",
        "* Booleans are three-state where noted: `true`, `false`, or `null` meaning unknown.\n",
        "* Every column is nullable unless its description says otherwise; a null always means "
        "the source did not provide the value, never that one was dropped.\n\n",
        "| Column | Type | Description |\n|---|---|---|\n",
    ]
    for name, field in InsiderTransaction.model_fields.items():
        desc = (field.description or "").replace("|", "\\|")
        lines.append(f"| `{name}` | {_type(CLEAN_SCHEMA[name])} | {desc} |\n")
    return "".join(lines)


def flags_md() -> str:
    lines = [
        HEADER,
        "# Quality flags\n\n",
        "Each record's `quality_status` is the most severe of its flags: INFO flags leave it "
        "`VALID`; WARNING, REVIEW_REQUIRED and INVALID set it to that status. Missing optional "
        "fields never make a record INVALID.\n\n",
        "| Code | Severity | What it means | Why it matters | What the engine does | Review |\n",
        "|---|---|---|---|---|---|\n",
    ]
    for f in FLAGS.values():
        lines.append(
            f"| `{f.code}` | {f.severity} | {f.title} | {f.why} | {f.action} | "
            f"{'yes' if f.review else 'no'} |\n"
        )
    lines.append("\n# Transaction codes\n\n")
    lines.append("| Code | Description | Group | Category | Confidence |\n|---|---|---|---|---|\n")
    for c in CODES.values():
        lines.append(
            f"| `{c.code}` | {c.description} | {c.group} | {c.category} | {c.confidence} |\n"
        )
    return "".join(lines)


OUTPUTS = {"schema.md": schema_md, "quality-flags.md": flags_md}


def main(check: bool = False) -> int:
    stale = []
    for name, render in OUTPUTS.items():
        path = DOCS / name
        text = render()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("Out of date: " + ", ".join(stale) + ". Run python scripts/generate_docs.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
